def test_top_k_zero_returns_nothing():
    result = find_evidence("mean relevance score quartiles sample [1].", REFS_SOURCE, top_k=0)

    assert result.passages == ()


def test_non_string_input_does_not_raise():
    assert find_evidence(b"x", b"y").status in tuple(RetrievalStatus)
    assert find_evidence(123, SOURCE).status in tuple(RetrievalStatus)


def test_source_label_is_carried_through():
    result = find_evidence("GPT-3.5 fabricated 55% of citations [1].", SOURCE, source_label="摘要")

    assert result.source_label == "摘要"


def test_a_subsection_heading_does_not_hide_the_main_section():
    source = ("# P\n\n## Results\n\n### Table 2. Mean relevance scores\n\n"
              "The mean relevance score was 7.84 across all quartiles of the sample.\n")

    result = find_evidence("mean relevance score across quartiles [1].", source, top_k=1)

    assert result.passages[0].section == "Results"
