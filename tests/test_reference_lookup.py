# 語料是從既有快取的 218 份開放存取全文裡抽出來的參考文獻行。樣式分布：
# APA／Harvard 括號年份 32%、年份在句尾 23%、numeric-[n] 20%、ACL 裸年份只有 1%。
# 所以括號年份那條比裸年份重要得多。


def test_apa_entry_with_the_year_in_brackets() -> None:
    meta = extract_reference_metadata(
        "Allen, K. A., Ryan, T., Gray, D. L., McInerney, D. M., & Waters, L. (2014). "
        "Social media use and social connectedness in adolescents. "
        "The Australian Educational and Developmental Psychologist, 31(1), 18–31."
    )
    assert meta.title == "Social media use and social connectedness in adolescents"
    assert meta.publication_year == 2014
    assert "paren-year" in meta.parse_note


def test_harvard_entry_without_a_comma_before_the_year() -> None:
    meta = extract_reference_metadata(
        "Huband S, Hingston P, While L, Barone L (2003) An evolution strategy with "
        "probabilistic mutation for multi-objective optimisation. Congress on Evolutionary Computation."
    )
    assert meta.title.startswith("An evolution strategy with probabilistic mutation")
    assert meta.publication_year == 2003


def test_the_arxiv_html_citation_key_prefix_is_stripped() -> None:
    """arXiv 的 HTML 書目會在每筆前面加引用鍵，不剝掉會把作者清單當成篇名。

    實測 7,294 筆語料裡有 9% 長這樣。
    """
    meta = extract_reference_metadata(
        "Müller et al. (2022) Müller, T., Evans, A., Schied, C., Keller, A. (2022). "
        "Instant neural graphics primitives with a multiresolution hash encoding. "
        "ACM Transactions on Graphics, 41(4)."
    )
    assert meta.title == "Instant neural graphics primitives with a multiresolution hash encoding"
    assert "Müller, T." not in meta.title


def test_a_page_number_is_not_accepted_as_a_title() -> None:
    """Vancouver 書目會讓裸年份那條抓到頁碼。字母太少就不是篇名。"""
    meta = extract_reference_metadata("Miljeteig I, Norheim OF. 2010. 035535. J Med Ethics 36.")
    assert meta.title == "", "頁碼不是篇名，寧可不給"
    assert "三種樣式都不符" in meta.parse_note


def test_a_venue_note_is_not_accepted_as_a_title() -> None:
    meta = extract_reference_metadata(
        "Marie-Catherine De Marneffe, Mandy Simons, and Judith Tonhauser. 2019. "
        "To appear in proceedings of Sinn und Bedeutung 23."
    )
    assert "To appear" not in meta.title


def test_a_genuinely_short_title_is_still_accepted() -> None:
    """防呆不可以把真的很短的篇名一起擋掉。"""
    meta = extract_reference_metadata(
        'Y. LeCun, Y. Bengio, and G. Hinton, "Deep learning," Nature, vol. 521, 2015.'
    )
    assert meta.title == "Deep learning"
