def test_same_ref_cited_twice_is_looked_up_once() -> None:
    claim = "First claim [47]. Second claim [47], [107]."
    refs = ('[47] "Verifiable credentials data model v1.1," W3C.\n'
            '[107] "Verifiable credentials data model v2.0," W3C.')
    pairs = build_citation_pairs(claim, refs)
    http = FakeHttp({})
    rows = run_method_a_pipeline(pairs, ReferenceLookupAdapter(http=http), MockJevAdapter())
    assert [r.pair.ref_number for r in rows] == [47, 47, 107]
    assert sum("search/match" in url for url in http.calls) == 2
    assert all(r.method_a.source_status is SourceStatus.NOT_FOUND for r in rows)


