def pair(ref_raw: str, ref_number: int = 1) -> CitationPair:
    return CitationPair(pair_id="p", claim_text="claim", citation_marker=f"[{ref_number}]",
                        ref_number=ref_number, ref_raw=ref_raw)


class FakeHttp:
    """Return canned responses by URL fragment or query/search value; 404 otherwise."""

    def __init__(self, routes: dict) -> None:
        self.routes = routes
        self.calls: list[str] = []

    def get(self, url, params=None, headers=None):
        self.calls.append(url)
        params = params or {}
        for key, response in self.routes.items():
            if key in url or key in (params.get("query"), params.get("search")):
                return response
        return 404, {"error": "not found"}, "HTTP 404"


