def test_cache_avoids_a_second_download(tmp_path: Path):
    downloader = FakeDownloader({"https://arxiv.org/html/1706.03762": page(ARXIV_HTML_PAGE)})
    cache = FullTextCache(tmp_path)
    meta = ReferenceMetadata(title="Attention", arxiv_id="1706.03762")

