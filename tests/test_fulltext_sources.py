class FakeDownloader:
    """照 URL 前綴回傳預先準備好的結果；沒對到的一律 404。"""

    def __init__(self, responses: dict[str, Download]) -> None:
        self.responses = responses
        self.calls: list[str] = []
        self.attempts: list[dict] = []

    def get(self, url: str, params: dict | None = None, *, accept: str = "") -> Download:
        self.calls.append(url)
        self.attempts.append({"endpoint": url})
        for prefix, response in self.responses.items():
            if url.startswith(prefix):
                return response
        return Download(status=404, error="HTTP 404")


def page(body: str, content_type: str = "text/html") -> Download:
    return Download(status=200, content_type=content_type, body=body.encode("utf-8"))


def openalex_work(locations: list[dict]) -> Download:
    import json

    payload = {"id": "https://openalex.org/W1", "best_oa_location": locations[0] if locations else None,
               "locations": locations}
    return Download(status=200, content_type="application/json",
                    body=json.dumps(payload).encode("utf-8"))


