def openalex_search(works: list[dict]) -> Download:
    import json

    return Download(status=200, content_type="application/json",
                    body=json.dumps({"results": works}).encode("utf-8"))


class _SequenceDownloader:
    """照 URL 前綴回傳結果，可以針對同一主機給不同結果。"""

    def __init__(self, responses: dict[str, Download], default: Download | None = None) -> None:
        self.responses = responses
        self.default = default or Download(status=404, error="HTTP 404")
        self.calls: list[str] = []
        self.attempts: list[dict] = []

    def get(self, url: str, params: dict | None = None, *, accept: str = "") -> Download:
        self.calls.append(url)
        self.attempts.append({"endpoint": url})
        for prefix, response in self.responses.items():
            if url.startswith(prefix):
                return response
        return self.default


